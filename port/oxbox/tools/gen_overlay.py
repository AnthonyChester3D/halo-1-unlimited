"""gen_overlay.py map out.ld: place OpenCE's input sections over the retail XBE's game code and globals, which the
retail libraries OpenCE links against never touch (found by a reachability scan of the retail XBE). Regions are
listed in port/oxbox/oxbox_overlay.h.

- .bss (zero-filled globals) goes first into the parts of the regions the XBE file does not back (the end of the
  retail .data section, which the loader zero-fills), then into the rest.
- What is left of the parts the file does back (the retail .text section, the start of .data) takes OpenCE's
  code, read-only data and data (.text.*, .rodata.*, .data.* input sections): mkxbe.py writes their bytes into
  the retail sections' raw data, and they come out of .cap16, which shrinks by as much (that is the memory won).
- oxbox_entry zeroes only the .bss parts (__ovlzN_start/_end, N < 16; link.ld PROVIDEs 0 for unused ones)."""
import re, sys
mp, out = sys.argv[1:3]
regions = [tuple(int(x, 16) for x in m) for m in
           re.findall(r'\{\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+)\s*\}', open(__import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)), '..', 'oxbox_overlay.h')).read())]
# the retail XBE's raw data ends: .text (0x11000, all raw) and .data (0x1f1260, raw 451612 bytes, then zero-filled)
DATA_RAW_END = 0x1f1260 + 451612
backed, zerofill = [], []
for a, b in regions:
    if a < 0x180e40: backed.append((a, b))
    elif b <= DATA_RAW_END: backed.append((a, b))
    elif a >= DATA_RAW_END: zerofill.append((a, b))
    else: backed.append((a, DATA_RAW_END & ~63)); zerofill.append(((DATA_RAW_END + 63) & ~63, b))

sections = {}   # output section -> [(size, align, file, input section)]
cur_top = None
for line in open(mp):
    p = line.split()
    top = re.match(r'^\s*\S+\s+\S+\s+\S+\s+\S+ (\S+)$', line)   # an output section: one space before its name
    if top: cur_top = top.group(1); sections.setdefault(cur_top, []); continue
    if cur_top and len(p) == 5:
        m = re.match(r'(.+\.o):\((\S+)\)$', p[4])
        if m: sections[cur_top].append((int(p[2], 16), int(p[3]), m.group(1), m.group(2)))

def aggregate(raw, minimum):
    # a file's COMMON symbols can only be placed together ("file.o"(COMMON)): one item, aligned sizes summed
    agg = {}
    for size, align, f, s in raw:
        k = (f, s)
        if k in agg:
            sz, al = agg[k]; agg[k] = (((sz + align - 1) & -align) + size, max(al, align))
        else: agg[k] = (size, align)
    return sorted(((sz, al, f, s) for (f, s), (sz, al) in agg.items() if sz >= minimum), reverse=True)

bss = aggregate(sections.get('.bss', []), 64)
# loadable: not the entry (it stays at the image start), not mergeable strings or constants (merged per output
# section), not plain .text/.rodata/.data (a file's unnamed section)
loadable = aggregate([x for name in ('.text', '.rodata', '.data') for x in sections.get(name, [])
                      if not x[3].startswith(('.text.oxbox_entry', '.rodata.str', '.rodata.cst'))
                      and x[3] not in ('.text', '.rodata', '.data')], 16)
# data at 16 bytes at least, as the .rodata/.data output sections happened to give it: the audio hardware reads
# sound data in place (progress_bar.c's compressed_monk_tone, a byte array, came out at an odd address in test
# 08 and played as noise on a real Xbox; xemu doesn't care)
loadable = [(sz, max(al, 16) if not s.startswith('.text') else al, f, s) for sz, al, f, s in loadable]

def pack(items, spaces):
    cur = [a for a, b in spaces]; placed = [[] for _ in spaces]; left = []
    for size, align, f, s in items:
        for i, (a, b) in enumerate(spaces):
            at = (cur[i] + align - 1) & -align
            if at + size <= b: placed[i].append((f, s)); cur[i] = at + size; break
        else: left.append((size, align, f, s))
    return cur, placed, left

SLACK = 256   # per space, for padding the estimate misses
zspaces = [(a, b - SLACK) for a, b in zerofill]
zcur, zplaced, bss_left = pack(bss, zspaces)
bspaces = [(a, b - SLACK) for a, b in backed]
bcur, bplaced, bss_left2 = pack(bss_left, bspaces)
# the loadable after the .bss in each backed space (its alignment padding estimated generously: 1/64 of it)
lspaces = [((c + 63) & -64, b - (b - c) // 64) for c, (a, b) in zip(bcur, bspaces)]
lcur, lplaced, load_left = pack(loadable, lspaces)

n = 0
with open(out, 'w') as o:
    o.write('/* generated by port/oxbox/tools/gen_overlay.py */\nSECTIONS {\n')
    for i, (a, b) in enumerate(zspaces):
        if not zplaced[i]: continue
        o.write(f'  .ovl{n} {a:#x} (NOLOAD) : {{\n')
        for f, s in zplaced[i]: o.write(f'    "{f}"({s})\n')
        o.write(f'  }}\n  ASSERT(ADDR(.ovl{n}) + SIZEOF(.ovl{n}) <= {b + SLACK:#x}, "overlay {n} overflows")\n')
        o.write(f'  __ovlz{n}_start = ADDR(.ovl{n}); __ovlz{n}_end = ADDR(.ovl{n}) + SIZEOF(.ovl{n});\n')
        n += 1
    for i, (a, b) in enumerate(bspaces):
        if not bplaced[i] and not lplaced[i]: continue
        z = n
        o.write(f'  .ovl{n} {a:#x} (NOLOAD) : {{\n')
        for f, s in bplaced[i]: o.write(f'    "{f}"({s})\n')
        o.write(f'  }}\n  __ovlz{n}_start = ADDR(.ovl{n}); __ovlz{n}_end = ADDR(.ovl{n}) + SIZEOF(.ovl{n});\n')
        n += 1
        if lplaced[i]:
            o.write(f'  .lovl{i} ALIGN(ADDR(.ovl{z}) + SIZEOF(.ovl{z}), 64) : {{\n')
            for f, s in lplaced[i]:
                if not s.startswith('.text'): o.write('    . = ALIGN(16);\n')
                o.write(f'    "{f}"({s})\n')
            o.write(f'  }}\n  ASSERT(ADDR(.lovl{i}) + SIZEOF(.lovl{i}) <= {b + SLACK:#x}, "loaded overlay {i} overflows")\n')
        else:
            o.write(f'  ASSERT(ADDR(.ovl{z}) + SIZEOF(.ovl{z}) <= {b + SLACK:#x}, "overlay {z} overflows")\n')
    o.write('}\n')
assert n <= 16, n
assert not bss_left2, f'{sum(x[0] for x in bss_left2)} bytes of .bss do not fit the overlay'
moved_bss = sum(x[0] for x in bss)
moved_load = sum(x[0] for x in loadable) - sum(x[0] for x in load_left)
total = sum(b - a for a, b in regions)
print(f'overlay: .bss {moved_bss // 1024} KB ({len(bss)} sections), code and data moved out of .cap16 {moved_load // 1024} KB '
      f'(left there {sum(x[0] for x in load_left) // 1024} KB), regions {total // 1024} KB '
      f'(zero-filled {sum(b - a for a, b in zerofill) // 1024} KB)')
