"""Writes port/oxbox/oxbox_config_table.h: the native ports' settings (port/linux/src/port_config.c's table: name, type,
default) with the Xbox build's own values where the PC defaults don't fit a console."""
import re
src = open('port/linux/src/port_config.c').read()
src = src.replace('CROUCH_KEYS', '"\\"Left Ctrl, C\\""')
ents = re.findall(r'\{\s*"([a-z0-9_.]+)",\s*_config_(boolean|integer|real|string),\s*("(?:[^"\\]|\\.)*"(?:\s*"(?:[^"\\]|\\.)*")*)', src)
XBOX = {
    'display.menus': '"\\"xbox\\""',              # the Xbox's own menus (ui.map), not the PC version's
    'display.high_res_hud': '"false"',            # the HUD and text as the Xbox draws them
    'display.high_res_text': '"false"',
    'display.interpolation': '"false"',           # frames at the game's 30 ticks, as on the Xbox
    'display.anti_aliasing': '"\\"off\\""',
    'display.per_pixel_lighting': '"false"',
    'display.shadow_resolution': '"128"',
    'audio.voice_chat': '"\\"off\\""',
    'audio.loose_sounds': '"false"',
    'network.map_share': '"false"', 'network.map_seed': '"false"', 'network.map_download': '"false"',
    'update.auto': '"false"', 'crash_reports.upload': '"\\"never\\""',
    'debug.memory_watch': '"false"', 'debug.telnet_console': '"false"',
    # system link only: no internet play, public listings or voice
    'network.online': '"false"', 'network.public_lobby': '"false"', 'network.host_public': '"false"',
    'network.voice_lobby': '"false"', 'network.allow_upnp': '"false"', 'network.join_from_clipboard': '"false"',
    # stock: no debug console on screen (debug.txt still has every line)
    'game.console_log': '"\\"none\\""',
    # OpenCE extras the Xbox build doesn't want: Custom Edition maps, vote kick and bans, the PC scoreboard panel
    'game.custom_edition': '"false"',
    'network.votekick': '"false"',
    'display.scoreboard_background': '"false"',
    # retail behaviour (test 02): grenade throws freeze the legs as on the Xbox, and no names over every
    # player's head (the game's own name of the player in view, game_engine.c, stays)
    'game.enhanced_animations': '"false"',
    'display.player_names': '"\\"none\\""',
    # stock camera (test 10): the observer's, not the PC's camera turned straight to the aim at drawing time
    'display.direct_camera': '"false"',
}
out = ['/* generated by port/oxbox/tools/gen_config.py from port/linux/src/port_config.c */']
for name, typ, val in ents:
    v = XBOX.get(name, val)
    v = ' '.join(re.findall(r'"(?:[^"\\]|\\.)*"', v))
    out.append(f'{{ "{name}", _oxbox_config_{typ}, {v} }},')
open('port/oxbox/oxbox_config_table.h', 'w').write('\n'.join(out) + '\n')
print(len(ents), 'settings')
